# k1lidar/gcode_meta.py - cosa stampa questo gcode? (filamento, temperature, primo strato)
#
# Gli slicer della famiglia Slic3r (OrcaSlicer, Creality Print, PrusaSlicer,
# SuperSlicer, Bambu Studio) scrivono in CODA al file un blocco "; chiave = valore"
# con tutte le impostazioni. Da li' leggiamo filamento e temperature, cosi' l'utente
# non deve impostarle a mano prima di stampare. Ripiego: i parametri di
# START_PRINT/PRINT_START (EXTRUDER_TEMP=, BED_TEMP=) e poi i registri/preset.
import os, re

TAIL_BYTES = 400 * 1024     # il blocco config di Orca su un K1 e' ~60 KB: margine ampio
HEAD_LINES = 3000

_KV = re.compile(r"^;\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$")
_START = re.compile(r"^\s*(START_PRINT|PRINT_START)\b(.*)$", re.I)
_PARAM = re.compile(r"([A-Z_]+)=([^\s]+)")

# temperatura piatto del primo strato per tipo di piatto (Orca/Bambu)
_PLATE = {
    "high temp plate": "hot_plate_temp_initial_layer",
    "textured pei plate": "textured_plate_temp_initial_layer",
    "cool plate": "cool_plate_temp_initial_layer",
    "engineering plate": "eng_plate_temp_initial_layer",
    "supertack plate": "supertack_plate_temp_initial_layer",
}


def _first(v):
    """Valori multi-estrusore ("220,220" o "\"a\";\"b\""): il primo, senza virgolette."""
    if v is None:
        return None
    v = v.strip()
    for sep in (";", ","):
        if sep in v:
            v = v.split(sep)[0]
            break
    return v.strip().strip('"').strip()


def _num(v):
    try:
        v = _first(v)
        return float(v.rstrip("%")) if v not in (None, "", "nil") else None
    except (TypeError, ValueError):
        return None


def _read_kv(path):
    kv = {}
    size = os.path.getsize(path)
    with open(path, "rb") as f:
        head = f.read(200 * 1024).decode("utf-8", "replace").splitlines()[:HEAD_LINES]
        f.seek(max(0, size - TAIL_BYTES))
        tail = f.read().decode("utf-8", "replace").splitlines()
    start = None
    for line in head + tail:
        m = _KV.match(line)
        if m:
            kv.setdefault(m.group(1), m.group(2))   # prima occorrenza vince (header)
            continue
        if start is None:
            m = _START.match(line)
            if m:
                start = dict((k.upper(), v) for k, v in _PARAM.findall(m.group(2).upper()))
    return kv, (start or {}), head


def read(path):
    """Metadati del gcode. Le chiavi assenti valgono None."""
    kv, start, head = _read_kv(path)
    slicer = None
    for line in head[:5]:
        m = re.search(r"generated by (\S+(?: \S+)?)", line, re.I)
        if m:
            slicer = m.group(1)
            break

    name = _first(kv.get("filament_settings_id"))
    ftype = _first(kv.get("filament_type"))
    nozzle = (_num(kv.get("first_layer_temperature")) or _num(kv.get("nozzle_temperature_initial_layer"))
              or _num(kv.get("nozzle_temperature")) or _num(kv.get("temperature"))
              or _num(start.get("EXTRUDER_TEMP")) or _num(start.get("HOTEND_TEMP")))
    nozzle_other = _num(kv.get("nozzle_temperature")) or _num(kv.get("temperature")) or nozzle

    bed = None
    plate = (_first(kv.get("curr_bed_type")) or "").lower()
    if plate in _PLATE:
        bed = _num(kv.get(_PLATE[plate]))
    bed = (bed or _num(kv.get("first_layer_bed_temperature")) or _num(kv.get("bed_temperature"))
           or _num(kv.get("hot_plate_temp_initial_layer")) or _num(start.get("BED_TEMP")))

    line_w = (_num(kv.get("initial_layer_line_width")) or _num(kv.get("first_layer_extrusion_width"))
              or _num(kv.get("line_width")))
    if line_w is not None and line_w > 5:      # "%": percentuale del diametro ugello
        line_w = None
    layer_h = _num(kv.get("initial_layer_print_height")) or _num(kv.get("first_layer_height"))

    pa_on = _first(kv.get("enable_pressure_advance"))
    return {
        "slicer": slicer,
        "printer_model": _first(kv.get("printer_model")),
        "filament_name": name,
        "filament_type": (ftype or "").upper() or None,
        "filament_vendor": _first(kv.get("filament_vendor")),
        "filament_colour": _first(kv.get("filament_colour")),
        "nozzle_temp": int(round(nozzle)) if nozzle else None,
        "nozzle_temp_other": int(round(nozzle_other)) if nozzle_other else None,
        "bed_temp": int(round(bed)) if bed else None,
        "first_layer_line_width": line_w,
        "first_layer_height": layer_h,
        # PA gestito dallo slicer: se attivo, il gcode contiene SET_PRESSURE_ADVANCE
        # e sovrascrive quello che applichiamo noi all'avvio.
        "slicer_pa_enabled": pa_on in ("1", "true", "True"),
        "slicer_pa": _num(kv.get("pressure_advance")),
    }


def filament_key(meta=None, name=None, nozzle=None):
    """Chiave delle calibrazioni: nome del filamento + temperatura ugello
    (il PA dipende dalla temperatura). Es. "Generic_PLA_T220"."""
    from .store import normalize_key
    n = name or (meta or {}).get("filament_name") or (meta or {}).get("filament_type") or "default"
    t = nozzle or (meta or {}).get("nozzle_temp_other") or (meta or {}).get("nozzle_temp")
    return normalize_key(n) + ("_T%d" % int(t) if t else "")


if __name__ == "__main__":
    import json, sys
    for p in sys.argv[1:]:
        d = read(p)
        d["key"] = filament_key(d)
        print(json.dumps(d, indent=2))
